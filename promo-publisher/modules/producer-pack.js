'use strict';

const fs = require('fs');
const path = require('path');
const { generatePsyPack } = require('./psy-pack');
const { zipDirectory } = require('./zip-store');
const { ensureDir, writeJson, OUTPUT_DIR } = require('./store');

function packRoot() {
  return path.join(OUTPUT_DIR, 'products');
}

function writeReadme(dir, manifest) {
  const text = [
    '# ShiBass Producer Pack v1',
    '',
    'Psytrance MIDI bank — E Phrygian Family (bass/kick stay Phrygian;',
    'leads/arps wander Dominant / Locrian) at 138–142 BPM.',
    'Mix when 50 files: 20 bass · 15 leads · 10 arps · 5 drums.',
    'Generated by psy_pack_v3 for Cubase / Ableton → Serum / Sylenth1.',
    '',
    `Files: ${manifest.midiCount} MIDI`,
    `Created: ${manifest.createdAt}`,
    '',
    '## How to use',
    '1. Drop a `_kick_` file on a drum/sampler track.',
    '2. Drop `_bass_` under Serum / Sylenth1 (route to Kick & Bass template).',
    '3. Drop `_lead_` / `_arp_` on a second instance for the hook.',
    '4. Keep human mix — this is a sketch bank, not a finished track.',
    '',
    '## License',
    'Royalty-free in your own productions. Do not resell the raw MIDI bank.',
    '',
    'Audix Records · ShiBass',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(dir, 'README.txt'), text, 'utf8');
}

function buildProducerPack(options = {}) {
  const midiCount = Number(options.count || 50);
  const generated = generatePsyPack({
    count: midiCount,
    bpm: options.bpm || 142,
    root: options.root || 'E',
    seed: options.seed,
  });

  const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const folderName = `ShiBass_Producer_Pack_v1_${stamp}`;
  const dir = path.join(packRoot(), folderName);
  const midiDir = path.join(dir, 'MIDI');
  ensureDir(midiDir);

  for (const file of generated.files) {
    fs.copyFileSync(file.path, path.join(midiDir, file.name));
  }

  const presetSlot = path.join(dir, 'Serum_Presets');
  ensureDir(presetSlot);
  fs.writeFileSync(
    path.join(presetSlot, 'DROP_YOUR_SERUM_FXP_HERE.txt'),
    'Copy 3–8 of your best Serum .fxp files here before listing on Audix.\n',
    'utf8',
  );

  const manifest = {
    product: 'ShiBass Producer Pack v1',
    createdAt: new Date().toISOString(),
    midiCount: generated.files.length,
    scale: generated.scale,
    bpm: generated.bpm,
    listingHint: 'Sell via Audix Records shop / Bandcamp / Gumroad. Price test: $19–29.',
  };
  writeReadme(dir, manifest);
  writeJson(path.join(dir, 'pack-manifest.json'), manifest);

  const zipPath = path.join(packRoot(), `${folderName}.zip`);
  const zip = zipDirectory(dir, zipPath);

  return {
    success: true,
    source: 'producer-pack',
    folder: dir,
    zipPath: zip.zipPath,
    bytes: zip.bytes,
    files: zip.files,
    midiCount: generated.files.length,
    listingHint: manifest.listingHint,
  };
}

module.exports = {
  buildProducerPack,
  packRoot,
};
